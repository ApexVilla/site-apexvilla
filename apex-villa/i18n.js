// Simple Text Replacer Strategy with WeakMap to protect dynamic text node indexes
window.currentLang = 'pt';
const originalTexts = new WeakMap();
const originalPlaceholders = new WeakMap();
const originalOptions = new WeakMap();
const originalHrefs = new WeakMap();

function normalizeText(str) {
  return str.replace(/\s+/g, ' ').trim();
}

function translateText(text) {
  const normalized = normalizeText(text);
  for (const [ptText, esText] of Object.entries(translations)) {
    if (normalizeText(ptText) === normalized) {
      return esText;
    }
  }

  // Sem correspondência exata devolvemos o português intacto, de propósito.
  // Aqui havia um fallback que trocava substrings soltas do dicionário dentro
  // da frase; como as chaves curtas ("e", "com", "Tecnologia ") batem no meio
  // de qualquer texto, ele produzia híbridos ("Planilhas y sistemas travam",
  // "tráfico pagado triplicou"). Português legível é melhor que isso, e vale
  // como sinal: se aparecer português no modo ES, falta a chave no dicionário.
  return text;
}

function getTextNodes(node) {
  let textNodes = [];
  if (node.nodeType === 3) {
    if (node.nodeValue.trim() !== "") textNodes.push(node);
  } else {
    for (let child of node.childNodes) {
      if (
        child.nodeName.toLowerCase() !== 'script' && 
        child.nodeName.toLowerCase() !== 'style' &&
        !(child.hasAttribute && child.hasAttribute('data-no-translate'))
      ) {
        textNodes.push(...getTextNodes(child));
      }
    }
  }
  return textNodes;
}

function initTranslations() {
  // Text nodes
  const nodes = getTextNodes(document.body);
  nodes.forEach((node) => {
    originalTexts.set(node, node.nodeValue);
  });

  // Placeholders
  document.querySelectorAll('[placeholder]').forEach((el) => {
    originalPlaceholders.set(el, el.placeholder);
  });

  // Select Options
  document.querySelectorAll('select option').forEach((el) => {
    originalOptions.set(el, el.textContent);
  });

  // WhatsApp Hrefs
  document.querySelectorAll('a[href*="wa.me"]').forEach((el) => {
    originalHrefs.set(el, el.href);
  });
}

function translatePage(lang) {
  // Translate text nodes
  const nodes = getTextNodes(document.body);
  nodes.forEach((node) => {
    const original = originalTexts.get(node);
    if (!original) return;
    
    if (lang === 'pt') {
      node.nodeValue = original;
    } else if (lang === 'es') {
      node.nodeValue = translateText(original);
    }
  });

  // Translate placeholders
  document.querySelectorAll('[placeholder]').forEach((el) => {
    const original = originalPlaceholders.get(el);
    if (!original) return;
    
    if (lang === 'pt') {
      el.placeholder = original;
    } else if (lang === 'es') {
      el.placeholder = translateText(original);
    }
  });

  // Translate options
  document.querySelectorAll('select option').forEach((el) => {
    const original = originalOptions.get(el);
    if (!original) return;
    
    if (lang === 'pt') {
      el.textContent = original;
    } else if (lang === 'es') {
      el.textContent = translateText(original);
    }
  });

  // Translate WhatsApp Hrefs
  document.querySelectorAll('a[href*="wa.me"]').forEach((el) => {
    const originalHref = originalHrefs.get(el);
    if (!originalHref) return;
    
    if (lang === 'pt') {
      el.href = originalHref;
    } else if (lang === 'es') {
      let newHref = originalHref;
      newHref = newHref.replace('Ol%C3%A1!+Quero+um+diagn%C3%B3stico+com+ApexVilla', '%C2%A1Hola!+Quero+un+diagn%C3%B3stico+con+ApexVilla');
      newHref = newHref.replace('Ol%C3%A1!+Quero+informacoes+sobre+ApexVilla', '%C2%A1Hola!+Quero+informaci%C3%B3n+sobre+ApexVilla');
      el.href = newHref;
    }
  });
}

document.addEventListener("DOMContentLoaded", () => {
  initTranslations();

  // Legacy support: ?lang=es translates the page in place when no static /es/ build exists (dev server)
  const urlLang = new URLSearchParams(location.search).get('lang');
  if (urlLang === 'es') {
    window.currentLang = 'es';
    translatePage('es');
    window.dispatchEvent(new CustomEvent('langChanged', { detail: 'es' }));
    document.querySelectorAll('.lang-btn').forEach(b => {
      b.classList.toggle('active', (b.dataset.lang || b.textContent.trim().toLowerCase()) === 'es');
    });
  }

  const langBtns = document.querySelectorAll('.lang-btn');
  langBtns.forEach(btn => {
    btn.addEventListener('click', (e) => {
      langBtns.forEach(b => b.classList.remove('active'));
      e.target.classList.add('active');
      const lang = e.target.dataset.lang;
      window.currentLang = lang;
      translatePage(lang);
      window.dispatchEvent(new CustomEvent('langChanged', { detail: lang }));
    });
  });
});
